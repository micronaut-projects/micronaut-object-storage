-- Micronaut Object Storage database storage: built-in tables for SQL Server 2019+.
-- Keys use a binary UTF-8 collation so that keys are case sensitive and listing order is byte order.

CREATE TABLE MN_OS_BUCKET (
    BUCKET_NAME VARCHAR(255) COLLATE Latin1_General_100_BIN2_UTF8 NOT NULL PRIMARY KEY,
    METADATA NVARCHAR(MAX),
    ATTRIBUTES NVARCHAR(MAX),
    CREATED_AT DATETIME2 NOT NULL
);

CREATE TABLE MN_OS_OBJECT (
    ID VARCHAR(36) NOT NULL PRIMARY KEY,
    BUCKET VARCHAR(255) COLLATE Latin1_General_100_BIN2_UTF8 NOT NULL,
    OBJECT_KEY VARCHAR(1024) COLLATE Latin1_General_100_BIN2_UTF8 NOT NULL,
    CONTENT_TYPE NVARCHAR(255),
    CONTENT_LENGTH BIGINT,
    ETAG VARCHAR(64),
    METADATA NVARCHAR(MAX),
    ATTRIBUTES NVARCHAR(MAX),
    CREATED_AT DATETIME2 NOT NULL,
    UPDATED_AT DATETIME2 NOT NULL,
    CONTENT VARBINARY(MAX),
    CONSTRAINT MN_OS_OBJECT_KEY_UQ UNIQUE (BUCKET, OBJECT_KEY)
);

CREATE TABLE MN_OS_CHUNK (
    CONTENT_ID VARCHAR(36) NOT NULL,
    SEQ BIGINT NOT NULL,
    DATA VARBINARY(MAX) NOT NULL,
    CONSTRAINT MN_OS_CHUNK_PK PRIMARY KEY (CONTENT_ID, SEQ)
);

CREATE TABLE MN_OS_UPLOAD (
    UPLOAD_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    BUCKET VARCHAR(255) COLLATE Latin1_General_100_BIN2_UTF8 NOT NULL,
    OBJECT_KEY VARCHAR(1024) COLLATE Latin1_General_100_BIN2_UTF8 NOT NULL,
    CONTENT_TYPE NVARCHAR(255),
    METADATA NVARCHAR(MAX),
    CREATED_AT DATETIME2 NOT NULL
);

CREATE INDEX MN_OS_UPLOAD_BUCKET_IDX ON MN_OS_UPLOAD (BUCKET);

CREATE TABLE MN_OS_UPLOAD_PART (
    UPLOAD_ID VARCHAR(36) NOT NULL,
    PART_NUMBER INT NOT NULL,
    CONTENT_ID VARCHAR(36) NOT NULL,
    ETAG VARCHAR(64),
    PART_SIZE BIGINT,
    CREATED_AT DATETIME2 NOT NULL,
    CONTENT VARBINARY(MAX),
    CONSTRAINT MN_OS_UPLOAD_PART_PK PRIMARY KEY (UPLOAD_ID, PART_NUMBER)
);
