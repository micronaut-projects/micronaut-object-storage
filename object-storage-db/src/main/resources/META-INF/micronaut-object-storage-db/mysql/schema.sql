-- Micronaut Object Storage database storage: built-in tables for MySQL 8 and MariaDB 10.6+.
-- Keys use the utf8mb4_bin collation so that listing order is byte order. A full 1024-character key exceeds the
-- InnoDB index size limit, so uniqueness is enforced on a SHA-256 hash of the key and listing uses a prefix index.

CREATE TABLE MN_OS_BUCKET (
    BUCKET_NAME VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL PRIMARY KEY,
    METADATA LONGTEXT,
    ATTRIBUTES LONGTEXT,
    CREATED_AT DATETIME(6) NOT NULL
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE MN_OS_OBJECT (
    ID VARCHAR(36) NOT NULL PRIMARY KEY,
    BUCKET VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    OBJECT_KEY VARCHAR(1024) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    KEY_HASH BINARY(32) AS (UNHEX(SHA2(OBJECT_KEY, 256))) STORED,
    CONTENT_TYPE VARCHAR(255),
    CONTENT_LENGTH BIGINT,
    ETAG VARCHAR(64),
    METADATA LONGTEXT,
    ATTRIBUTES LONGTEXT,
    CREATED_AT DATETIME(6) NOT NULL,
    UPDATED_AT DATETIME(6) NOT NULL,
    CONTENT LONGBLOB,
    CONSTRAINT MN_OS_OBJECT_KEY_UQ UNIQUE (BUCKET, KEY_HASH),
    INDEX MN_OS_OBJECT_KEY_IDX (BUCKET, OBJECT_KEY(512))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE MN_OS_CHUNK (
    CONTENT_ID VARCHAR(36) NOT NULL,
    SEQ BIGINT NOT NULL,
    DATA LONGBLOB NOT NULL,
    CONSTRAINT MN_OS_CHUNK_PK PRIMARY KEY (CONTENT_ID, SEQ)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE MN_OS_UPLOAD (
    UPLOAD_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    BUCKET VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    OBJECT_KEY VARCHAR(1024) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    CONTENT_TYPE VARCHAR(255),
    METADATA LONGTEXT,
    CREATED_AT DATETIME(6) NOT NULL,
    INDEX MN_OS_UPLOAD_BUCKET_IDX (BUCKET)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE MN_OS_UPLOAD_PART (
    UPLOAD_ID VARCHAR(36) NOT NULL,
    PART_NUMBER INT NOT NULL,
    CONTENT_ID VARCHAR(36) NOT NULL,
    ETAG VARCHAR(64),
    PART_SIZE BIGINT,
    CREATED_AT DATETIME(6) NOT NULL,
    CONTENT LONGBLOB,
    CONSTRAINT MN_OS_UPLOAD_PART_PK PRIMARY KEY (UPLOAD_ID, PART_NUMBER)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;
