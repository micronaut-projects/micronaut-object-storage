-- Micronaut Object Storage database storage: built-in tables for Oracle Database 23ai.
-- Content is stored either in the SecureFile CONTENT column (with the Oracle module) or as chunk rows
-- (MN_OS_CHUNK). Metadata uses the native JSON type. Keys are compared with NLSSORT(..., 'NLS_SORT=BINARY')
-- because column collations require MAX_STRING_SIZE=EXTENDED.

CREATE TABLE MN_OS_BUCKET (
    BUCKET_NAME VARCHAR2(255 CHAR) NOT NULL PRIMARY KEY,
    METADATA JSON,
    ATTRIBUTES JSON,
    CREATED_AT TIMESTAMP NOT NULL
);

CREATE TABLE MN_OS_OBJECT (
    ID VARCHAR2(36 CHAR) NOT NULL PRIMARY KEY,
    BUCKET VARCHAR2(255 CHAR) NOT NULL,
    OBJECT_KEY VARCHAR2(1024 CHAR) NOT NULL,
    CONTENT_TYPE VARCHAR2(255 CHAR),
    CONTENT_LENGTH NUMBER(19),
    ETAG VARCHAR2(64 CHAR),
    METADATA JSON,
    ATTRIBUTES JSON,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    CONTENT BLOB,
    CONSTRAINT MN_OS_OBJECT_KEY_UQ UNIQUE (BUCKET, OBJECT_KEY)
) LOB (CONTENT) STORE AS SECUREFILE;

CREATE TABLE MN_OS_CHUNK (
    CONTENT_ID VARCHAR2(36 CHAR) NOT NULL,
    SEQ NUMBER(19) NOT NULL,
    DATA BLOB NOT NULL,
    CONSTRAINT MN_OS_CHUNK_PK PRIMARY KEY (CONTENT_ID, SEQ)
) LOB (DATA) STORE AS SECUREFILE;

CREATE TABLE MN_OS_UPLOAD (
    UPLOAD_ID VARCHAR2(36 CHAR) NOT NULL PRIMARY KEY,
    BUCKET VARCHAR2(255 CHAR) NOT NULL,
    OBJECT_KEY VARCHAR2(1024 CHAR) NOT NULL,
    CONTENT_TYPE VARCHAR2(255 CHAR),
    METADATA JSON,
    CREATED_AT TIMESTAMP NOT NULL
);

CREATE INDEX MN_OS_UPLOAD_BUCKET_IDX ON MN_OS_UPLOAD (BUCKET);

CREATE TABLE MN_OS_UPLOAD_PART (
    UPLOAD_ID VARCHAR2(36 CHAR) NOT NULL,
    PART_NUMBER NUMBER(10) NOT NULL,
    CONTENT_ID VARCHAR2(36 CHAR) NOT NULL,
    ETAG VARCHAR2(64 CHAR),
    PART_SIZE NUMBER(19),
    CREATED_AT TIMESTAMP NOT NULL,
    CONTENT BLOB,
    CONSTRAINT MN_OS_UPLOAD_PART_PK PRIMARY KEY (UPLOAD_ID, PART_NUMBER)
) LOB (CONTENT) STORE AS SECUREFILE;
